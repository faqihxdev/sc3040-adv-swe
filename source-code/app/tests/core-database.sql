begin;
do $$
declare owner_id uuid := gen_random_uuid(); member_id uuid := gen_random_uuid(); outsider_id uuid := gen_random_uuid();
 h1 uuid; h2 uuid; code text; old_code text; a public.inventory; b public.inventory; foreign_item public.inventory;
 session_id uuid := gen_random_uuid(); saved uuid; original_version int; failed boolean; count_before int;
 changes jsonb; result jsonb;
begin
 insert into auth.users(id,email) values(owner_id,owner_id::text || '@tests.invalid'),(member_id,member_id::text || '@tests.invalid'),(outsider_id,outsider_id::text || '@tests.invalid');
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 h1 := (public.mutate('create_household','{"name":"Core tests"}')->>'id')::uuid;
 old_code := public.mutate('invite','{}')->>'code';
 code := public.mutate('invite','{}')->>'code';
 perform set_config('request.jwt.claim.sub',member_id::text,true);
 failed := false;
 begin perform public.mutate('join_household',jsonb_build_object('code',old_code)); exception when sqlstate 'P0001' then failed := true; end;
 assert failed, 'Replaced join code was accepted';
 perform public.mutate('join_household',jsonb_build_object('code',code));
 perform set_config('request.jwt.claim.sub',outsider_id::text,true);
 h2 := (public.mutate('create_household','{"name":"Other test kitchen"}')->>'id')::uuid;
 result := public.mutate('add_item','{"name":"Other rice","stock":3,"expiry_date":"2026-10-01","category":"Grains","location":"Pantry"}');
 select * into foreign_item from public.inventory where id=(result->>'id')::uuid;
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 result := public.mutate('add_item','{"name":"Rice","stock":3,"expiry_date":"2026-10-01","category":"Grains","location":"Pantry"}');
 select * into a from public.inventory where id=(result->>'id')::uuid;
 result := public.mutate('add_item','{"name":"Eggs","stock":3,"expiry_date":"2026-09-01","category":"Protein","location":"Fridge"}');
 select * into b from public.inventory where id=(result->>'id')::uuid;
 assert (select count(*) from public.activity where household_id=h1 and actor_id=owner_id and action='add_item')=2, 'Missing actor/time inventory history';
 assert (select 'Pantry'=any(locations) from public.households where id=h1), 'Storage tag not reusable';

 -- Exercise actual authenticated read permissions, not superuser-only filtering.
 perform set_config('role','authenticated',true);
 assert (select count(*) from public.households)=1, 'Household RLS leak';
 assert (select count(*) from public.inventory)=2, 'Inventory RLS leak';
 assert (select count(*) from public.inventory where id=foreign_item.id)=0, 'Foreign item visible';
 failed:=false;
 begin perform public.mutate('edit_item',to_jsonb(foreign_item)); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Foreign item editable';
 failed:=false;
 begin update public.inventory set stock=5 where id=a.id; exception when insufficient_privilege then failed:=true; end;
 assert failed, 'Direct inventory writes bypass RPC';
 perform set_config('role','postgres',true);

 changes:=jsonb_build_array(jsonb_build_object('id',a.id,'version',a.version,'stock',3,'used',false,'discarded',false),jsonb_build_object('id',b.id,'version',b.version+1,'stock',1,'used',true,'discarded',false));
 count_before:=(select count(*) from public.outcomes where household_id=h1);
 failed:=false;
 begin perform public.confirm_meal(owner_id,h1,session_id,'{"name":"Rice meal"}',changes); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Stale confirmation accepted';
 assert (select version from public.inventory where id=a.id)=a.version, 'Failed confirmation partially updated stock';
 assert (select count(*) from public.outcomes where household_id=h1)=count_before, 'Failed confirmation stored an outcome';
 changes:=jsonb_build_array(jsonb_build_object('id',a.id,'version',a.version,'stock',3,'used',false,'discarded',false),jsonb_build_object('id',b.id,'version',b.version,'stock',1,'used',true,'discarded',true));
 saved:=public.confirm_meal(owner_id,h1,session_id,'{"name":"Rice meal"}',changes);
 assert saved=public.confirm_meal(owner_id,h1,session_id,'{"name":"Rice meal"}',changes), 'Duplicate confirmation not idempotent';
 assert (select count(*) from public.outcomes where household_id=h1)=count_before+1, 'Duplicate outcome stored';
 assert (select stock from public.inventory where id=a.id)=3, 'Default remaining stock changed';
 assert (select stock from public.inventory where id=b.id)=1, 'Confirmed stock not saved';
 assert (select ingredients->1->>'name' from public.outcomes where id=saved)='Eggs', 'Historical name snapshot missing';
 assert (select (ingredients->1->>'used')::boolean and (ingredients->1->>'discarded')::boolean from public.outcomes where id=saved), 'Use/discard flags conflated';
 failed:=false;
 begin perform public.confirm_meal(outsider_id,h1,gen_random_uuid(),'{}',changes); exception when insufficient_privilege then failed:=true; end;
 assert failed, 'Outsider confirmation accepted';
 failed:=false;
 begin perform public.confirm_meal(owner_id,h1,session_id,'{"name":"Different meal"}',changes); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Changed recipe reused confirmed session';
 assert not has_function_privilege('authenticated','public.confirm_meal(uuid,uuid,uuid,jsonb,jsonb)','execute'), 'Client can forge a confirmed recipe';

 -- Stale single-item edits and undo must not overwrite a later cooking write.
 failed:=false;
 begin perform public.mutate('edit_item',to_jsonb(b)); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Stale edit accepted';
 failed:=false;
 begin perform public.mutate('undo','{}'); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Undo overwrote cooking confirmation';
 select * into a from public.inventory where id=a.id;
 perform public.mutate('remove_item',jsonb_build_object('id',a.id,'version',a.version));
 perform public.mutate('undo','{}');
 assert not (select deleted from public.inventory where id=a.id), 'Safe removal undo failed';

 original_version:=(select version from public.households where id=h1);
 failed:=false;
 begin perform public.mutate('leave',jsonb_build_object('version',original_version)); exception when sqlstate 'P0001' then failed:=true; end;
 assert failed, 'Owner left an ownerless household';
 perform set_config('request.jwt.claim.sub',member_id::text,true);
 failed:=false;
 begin perform public.mutate('transfer',jsonb_build_object('version',original_version,'user_id',owner_id)); exception when insufficient_privilege then failed:=true; end;
 assert failed, 'Member can transfer ownership';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 failed:=false;
 begin perform public.mutate('transfer',jsonb_build_object('version',original_version-1,'user_id',member_id)); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Stale ownership change accepted';
 perform public.mutate('transfer',jsonb_build_object('version',original_version,'user_id',member_id));
 assert (select hh.owner_id from public.households hh where id=h1)=member_id, 'Ownership transfer failed';
 perform set_config('request.jwt.claim.sub',member_id::text,true);
 perform public.mutate('remove_member',jsonb_build_object('version',original_version+1,'user_id',owner_id));
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 perform set_config('role','authenticated',true);
 assert (select count(*) from public.inventory)=0 and (select count(*) from public.outcomes)=0, 'Removed member retains access';
 perform set_config('role','postgres',true);
 perform set_config('request.jwt.claim.sub',member_id::text,true);
 failed:=false;
 begin perform public.mutate('delete_household',jsonb_build_object('version',original_version+2,'confirmation','Wrong name')); exception when sqlstate 'P0001' then failed:=true; end;
 assert failed, 'Deletion confirmation bypassed';
 perform public.mutate('delete_household',jsonb_build_object('version',original_version+2,'confirmation','Core tests'));
 assert not exists(select 1 from public.inventory where household_id=h1), 'Deleted household retained inventory';
 assert not exists(select 1 from public.outcomes where household_id=h1), 'Deleted household retained outcomes';
 assert not exists(select 1 from public.memberships where household_id=h1), 'Deleted household retained membership';
 raise notice 'PASS: core CRUD/undo, history, RLS, confirmation atomicity/idempotency, flags, snapshots, permissions, membership/version/deletion rules';
end $$;
rollback;
