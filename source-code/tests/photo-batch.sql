begin;
do $$
declare uid uuid; teammate uuid; hid uuid; rid uuid:=gen_random_uuid(); batch jsonb; saved jsonb; retried jsonb;
 before_count int; failed boolean; first_id uuid; edited public.inventory;
begin
 select id into uid from auth.users where email='alex@useeatnow.test';
 select id into teammate from auth.users where email='sam@useeatnow.test';
 if uid is null or teammate is null then raise exception 'Run db:seed before this test.'; end if;
 select household_id into hid from public.memberships where user_id=uid;
 perform set_config('request.jwt.claim.sub',uid::text,true);
 batch := '[{"name":"Photo test tomato","stock":3,"expiry_date":"2026-10-05","category":"Vegetables","location":"Fridge"},{"name":"Photo test onion","stock":2,"expiry_date":"2026-10-06","category":"Vegetables","location":"Pantry"}]';
 select count(*) into before_count from public.inventory where household_id=hid and not deleted;
 saved := public.add_inventory_batch(hid,rid,batch);
 retried := public.add_inventory_batch(hid,rid,batch);
 assert saved=retried, 'Retry must return the original IDs';
 assert (select count(*) from public.inventory where household_id=hid and not deleted)=before_count+2, 'Retry duplicated inventory';
 failed:=false;
 begin perform public.add_inventory_batch(hid,rid,jsonb_set(batch,'{0,name}','"Different"')); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Changed payload reused a request ID';
 failed:=false;
 begin perform public.add_inventory_batch(gen_random_uuid(),gen_random_uuid(),batch); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Wrong household accepted';
 failed:=false;
 begin perform public.add_inventory_batch(hid,gen_random_uuid(),jsonb_set(batch,'{1,expiry_date}','"2026-02-30"')); exception when others then failed:=true; end;
 assert failed, 'Invalid date accepted';
 assert (select count(*) from public.inventory where household_id=hid and not deleted)=before_count+2, 'Invalid row left a partial batch';
 perform public.mutate('undo','{}');
 assert (select count(*) from public.inventory where household_id=hid and not deleted)=before_count, 'Batch undo was partial';
 failed:=false;
 begin perform public.add_inventory_batch(hid,gen_random_uuid(),'[]'); exception when sqlstate 'P0001' then failed:=true; end;
 assert failed, 'Empty batch accepted';
 failed:=false;
 begin perform public.add_inventory_batch(hid,gen_random_uuid(),(select jsonb_agg(batch->0) from generate_series(1,11))); exception when sqlstate 'P0001' then failed:=true; end;
 assert failed, 'More than ten entries accepted';
 saved:=public.add_inventory_batch(hid,gen_random_uuid(),(select jsonb_agg(batch->0) from generate_series(1,10)));
 assert (saved->>'count')::int=10, 'Ten-entry batch rejected';
 perform public.mutate('undo','{}');
 assert (select count(*) from public.inventory where household_id=hid and not deleted)=before_count, 'Ten-entry undo was partial';
 rid:=gen_random_uuid(); saved:=public.add_inventory_batch(hid,rid,batch); first_id:=(saved->'ids'->>0)::uuid;
 perform set_config('request.jwt.claim.sub',teammate::text,true);
 select * into edited from public.inventory where id=first_id;
 perform public.mutate('edit_item',to_jsonb(edited) || '{"stock":1}');
 perform set_config('request.jwt.claim.sub',uid::text,true);
 failed:=false;
 begin perform public.mutate('undo','{}'); exception when sqlstate 'PT409' then failed:=true; end;
 assert failed, 'Stale batch undo accepted';
 assert (select count(*) from public.inventory where household_id=hid and not deleted)=before_count+2, 'Stale undo removed part of the batch';
 perform set_config('request.jwt.claim.sub','',true);
 failed:=false;
 begin perform public.add_inventory_batch(hid,gen_random_uuid(),batch); exception when sqlstate '42501' then failed:=true; end;
 assert failed, 'Anonymous save accepted';
 assert not has_function_privilege('authenticated','private.mutate_single(text,jsonb)','execute'), 'Old undo route is accessible';
 assert not has_table_privilege('authenticated','private.inventory_imports','select'), 'Import ledger is exposed';
 raise notice 'PASS: atomicity, idempotency, household isolation, batch limits, batch undo, stale undo, authentication, private permissions';
end $$;
rollback;
